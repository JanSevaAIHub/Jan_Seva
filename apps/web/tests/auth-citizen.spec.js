test('recovery request, provider callback and new password work with isolated Auth double', async ({ page }) => {
  await page.goto('/')
  const dialog = await citizenDialog(page)
  await dialog.getByRole('button', { name: 'Forgot password?', exact: true }).click()
  const email = `reset-${Date.now()}@example.test`
  const oldPassword = 'old-synthetic-password', newPassword = 'new-synthetic-password'
  // Create only an Auth identity; application profile creation remains in /me.
  await page.request.post('http://127.0.0.1:8765/auth/v1/signup', { data: { email, password: oldPassword } })
  await dialog.getByLabel('Email').fill(email)
  await dialog.getByRole('button', { name: 'Send reset link' }).click()
  await expect(dialog.getByRole('status')).toContainText('If an account exists')
  const session = await (await page.request.post('http://127.0.0.1:8765/auth/v1/token?grant_type=password', { data: { email, password: oldPassword } })).json()
  const fragment = new URLSearchParams({ access_token: session.access_token, refresh_token: session.refresh_token, type: 'recovery', expires_in: '3600', token_type: 'bearer' })
  await page.goto(`/auth/reset#${fragment}`)
  const reset = page.getByRole('dialog')
  await expect(reset.getByRole('heading', { name: 'Choose a new password' })).toBeVisible()
  await reset.getByLabel('Password', { exact: true }).fill(newPassword)
  await reset.getByLabel('Confirm password', { exact: true }).fill(newPassword)
  await reset.getByRole('button', { name: 'Update password', exact: true }).click()
  await expect(reset.getByRole('status')).toContainText('Password updated')
  const oldLogin = await page.request.post('http://127.0.0.1:8765/auth/v1/token?grant_type=password', { data: { email, password: oldPassword } })
  expect(oldLogin.status()).toBe(400)
  const newLogin = await page.request.post('http://127.0.0.1:8765/auth/v1/token?grant_type=password', { data: { email, password: newPassword } })
  expect(newLogin.status()).toBe(200)
  expect(new URL(page.url()).hash).toBe('')
})

test('saved package opens a safe portal and persists unverified channel/date/reference', async ({ page, context }) => {
  await page.goto('/complaints/new')
  await login(page, 'citizen')
  await page.getByRole('button', { name: 'Load sample', exact: true }).click()
  await page.getByRole('button', { name: 'Submit Complaint', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm & Create Ticket' }).click()
  await page.getByRole('button', { name: 'View Package', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const portal = dialog.getByRole('link', { name: 'CPGRAMS National Portal' })
  await expect(portal).toHaveAttribute('target', '_blank')
  await expect(portal).toHaveAttribute('rel', 'noopener noreferrer')
  // Isolated navigation double: do not contact or mutate a government account.
  await context.route('https://pgportal.gov.in/**', route => route.fulfill({ body: '<p>Official navigation test double</p>', contentType: 'text/html' }))
  const popup = page.waitForEvent('popup')
  await portal.click()
  await (await popup).close()
  await expect(dialog.getByText('Government filing: NOT_FILED', { exact: false })).toBeVisible()
  await dialog.getByLabel('Already filed officially? Record Government Reference ID').fill('SYNTHETIC-REFERENCE-42')
  await dialog.getByLabel('Official filing channel').selectOption('CPGRAMS')
  await dialog.getByLabel('Official submission date (optional)').fill('2026-01-02')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.goto('/requests')
  await page.getByRole('link', { name: 'View details & audit history' }).first().click()
  await expect(page.getByText('User-provided reference: SYNTHETIC-REFERENCE-42 (unverified)')).toBeVisible()
  await expect(page.getByText('Reported submission date: 2026-01-02')).toBeVisible()
  await expect(page.getByText('Filing channel: CPGRAMS', { exact: true })).toBeVisible()
})

test('analysis outage preserves editable form and cannot block confirmed complaint creation', async ({ page }) => {
  await page.goto('/complaints/new')
  await login(page, 'citizen')
  await page.getByRole('button', { name: 'Load sample', exact: true }).click()
  const description = page.getByPlaceholder('Describe what happened, exact location landmark, and when it started...')
  const supplied = await description.inputValue()
  await page.route('**/api/complaints/analyze', route => route.fulfill({ status: 503, json: { detail: { code: 'ANALYSIS_UNAVAILABLE', message: 'Synthetic analysis outage' } } }))
  await page.getByRole('button', { name: 'Analyze complaint (optional)', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'You can still review and save' })).toBeVisible()
  await expect(description).toHaveValue(supplied)
  await page.locator('main select').selectOption('Roads & Potholes')
  await page.getByRole('button', { name: 'Submit Complaint', exact: true }).click()
  const saved = page.waitForResponse(r => r.url().endsWith('/api/complaints') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Confirm & Create Ticket' }).click()
  expect((await saved).status()).toBe(201)
})

