import { test, expect } from '@playwright/test'
import { login } from './helpers/auth.js'

test('officer status and locality filters update the queue and counters together', async ({ page }) => {
  await page.goto('/complaints/new')
  await login(page, 'citizen')
  await page.getByRole('button', { name: 'Load sample', exact: true }).click()
  await page.getByLabel('Locality', { exact: true }).fill('Audit Filter Ward')
  await page.getByRole('button', { name: 'Submit Complaint', exact: true }).click()
  const created = page.waitForResponse(r => r.url().endsWith('/api/complaints') && r.request().method() === 'POST' && r.status() === 201)
  await page.getByRole('button', { name: 'Confirm & Create Ticket' }).click()
  const ticket = await (await created).json()
  await expect(page.getByRole('dialog')).toBeHidden()
  await login(page, 'officer')
  await page.goto('/officer')
  const row = page.getByRole('row').filter({ hasText: ticket.id })
  await expect(row).toBeVisible()
  await page.getByLabel('Filter by locality').fill('audit filter ward')
  await page.getByLabel('Filter by status').selectOption('RESOLVED')
  await expect(row).toHaveCount(0)
  await expect(page.getByText('No assigned complaints match these filters.')).toBeVisible()
  const total = page.getByText('Total Requests', { exact: true }).locator('../..')
  await expect(total.locator('.text-2xl')).toHaveText('0')
  await page.getByLabel('Filter by status').selectOption('LOCAL_SUBMITTED')
  await expect(row).toBeVisible()
  await page.getByLabel('Filter by category').selectOption('road')
  await expect(row).toHaveCount(0)
  await page.getByLabel('Filter by category').selectOption('all')
  await expect(row).toBeVisible()
  await page.getByLabel('Filter by locality').fill('No matching audit ward')
  await expect(row).toHaveCount(0)
})
